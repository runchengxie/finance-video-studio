import {readFile} from 'node:fs/promises';
import {schema,csvData} from './core.js';
import {render} from './render.js';
import {loadReview} from './review-io.js';
const [input,review,out,audio,csv]=process.argv.slice(2);
if(!input||!review||!out) throw new Error('Usage: npm run render -- project.json approval.json ABSOLUTE_OUTPUT [local-audio] [data.csv]. For the fixed synthetic example use npm run demo.');
const raw:unknown=JSON.parse(await readFile(input,'utf8'));
const p=schema.parse(raw);
if(csv) p.data=csvData(await readFile(csv,'utf8'));
await render(schema.parse(p),out,audio,await loadReview(review));
