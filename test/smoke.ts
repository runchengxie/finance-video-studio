import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {schema} from '../src/core.js';
import {renderDemo,ffmpeg} from '../src/render.js';
const out=process.argv[2];
if(!out) throw new Error('Supply an empty absolute external output directory');
const p=schema.parse(JSON.parse(await readFile('examples/demo.json','utf8')));
p.frames=90;p.captions=p.captions.map((c,i)=>({...c,start:i*30,end:(i+1)*30}));
await renderDemo(out,undefined,'bar-smoke');
const probe=JSON.parse(execFileSync(process.env.FFPROBE_PATH??'ffprobe',['-v','error','-count_frames','-show_streams','-show_format','-of','json',path.join(out,'video.mp4')],{encoding:'utf8'}));
const v=probe.streams[0];
assert.equal(v.codec_name,'h264');assert.equal(v.width,1280);assert.equal(v.height,720);assert.equal(v.pix_fmt,'yuv420p');assert.equal(v.r_frame_rate,'30/1');assert.equal(Number(v.nb_read_frames),90);assert.ok(Math.abs(Number(probe.format.duration)-3)<0.05);
ffmpeg(['-v','error','-xerror','-i',path.join(out,'video.mp4'),'-f','null','-']);
await writeFile(path.join(out,'probe.json'),JSON.stringify(probe,null,2));
console.log('90 frames encoded, probed and decoded; silent smoke passed');
const tone=path.join(out,'synthetic-test-tone.wav');
ffmpeg(['-y','-f','lavfi','-i','sine=frequency=440:duration=1','-c:a','pcm_s16le',tone]);
const lineOut=path.join(out,'line-audio');
await renderDemo(lineOut,tone,'line-smoke');
const lineProbe=JSON.parse(execFileSync(process.env.FFPROBE_PATH??'ffprobe',['-v','error','-count_frames','-show_streams','-show_format','-of','json',path.join(lineOut,'video.mp4')],{encoding:'utf8'}));
assert.equal(lineProbe.streams.find((s:{codec_type:string})=>s.codec_type==='audio').codec_name,'aac');
assert.equal(Number(lineProbe.streams.find((s:{codec_type:string})=>s.codec_type==='video').nb_read_frames),60);
assert.ok(Math.abs(Number(lineProbe.format.duration)-2)<0.1);
ffmpeg(['-v','error','-xerror','-i',path.join(lineOut,'video.mp4'),'-f','null','-']);
console.log('60-frame line chart and padded local synthetic audio passed');
